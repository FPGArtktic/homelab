#!/usr/bin/env bash
# Installs the homelab on the host as the normal user (no root needed).
# Run from the repo checkout on the server: ~/homelab/scripts/install.sh
# Idempotent: safe to re-run after `git pull` / rsync.
set -euo pipefail

# Root would write secrets to /root and units to the wrong user. Refuse early.
if [[ $EUID -eq 0 ]]; then
  echo "Do not run as root (no sudo): run as the homelab user. Root step is host-setup-root.sh." >&2
  exit 1
fi

REPO="$(cd "$(dirname "$0")/.." && pwd)"
QUADLET_DIR="${HOME}/.config/containers/systemd"
UNIT_DIR="${HOME}/.config/systemd/user"

# Persistent bind-mount targets (named volumes are created by Podman itself).
mkdir -p "$QUADLET_DIR" "$UNIT_DIR" \
  "$REPO/data/files" "$REPO/data/filebrowser/database" \
  "$REPO/data/filebrowser/config" "$REPO/data/archivebox"

"$REPO/scripts/gen-env.sh"

# Autostart after power-on needs linger (user services run without a login).
if [[ $(loginctl show-user "$USER" -p Linger --value) != yes ]]; then
  if ! loginctl enable-linger "$USER" 2>/dev/null; then
    echo "Linger is off and could not be enabled without root." >&2
    echo "Run once as root: loginctl enable-linger $USER" >&2
    exit 1
  fi
fi

# avahi-publish (avahi-utils) installs only with root. Fetch the .deb as a normal
# user and unpack it under ~/.local; avahi-daemon itself is already installed.
AVAHI_DIR="${HOME}/.local/avahi-utils"
if [[ ! -x $AVAHI_DIR/usr/bin/avahi-publish ]] && ! command -v avahi-publish >/dev/null; then
  tmp=$(mktemp -d)
  (cd "$tmp" && apt-get download avahi-utils >/dev/null)
  dpkg -x "$tmp"/avahi-utils_*.deb "$AVAHI_DIR"
  rm -rf "$tmp"
fi

# Copy units and remember which ones changed: GitLab takes minutes to boot, so
# unchanged services must not be restarted on every deploy.
changed=()
for f in "$REPO"/quadlet/*; do
  name=$(basename "$f")
  if ! cmp -s "$f" "$QUADLET_DIR/$name"; then cp "$f" "$QUADLET_DIR/$name"; changed+=("$name"); fi
done
for f in "$REPO"/systemd/*.service; do
  name=$(basename "$f")
  if ! cmp -s "$f" "$UNIT_DIR/$name"; then cp "$f" "$UNIT_DIR/$name"; changed+=("$name"); fi
done

systemctl --user daemon-reload
systemctl --user enable --now podman.socket

# Quadlet units are generated by systemd, so they cannot be `enable`d by hand:
# the [Install] WantedBy in each .container wires them to default.target.
SERVICES=(nginx homepage portainer dozzle netdata filebrowser archivebox redis gitlab gitlab-runner forgejo forgejo-runner node-exporter cadvisor prometheus grafana mikrodash mattermost-db mattermost gitlab-relay)
rc=0   # any unit that fails to start/restart is reported and makes the script exit non-zero
systemctl --user start "${SERVICES[@]/%/.service}" homelab-mdns.service || rc=1

# Restart only what changed. A network change recreates every container.
restart=()
if [[ " ${changed[*]} " == *" homelab.network "* ]]; then
  restart=("${SERVICES[@]/%/.service}")
else
  for name in "${changed[@]}"; do
    case $name in
      *.container) restart+=("${name%.container}.service") ;;
      homelab-mdns.service) restart+=("$name") ;;
    esac
  done
fi
if (( ${#restart[@]} )); then systemctl --user restart "${restart[@]}" || rc=1; fi

# gitlab.rb is a bind mount, not a unit file, so track it by checksum: GitLab only
# re-reads it on start (reconfigure), and that restart is slow.
GL_SUM="${HOME}/.config/homelab/gitlab.rb.sha256"
sum=$(sha256sum "$REPO/gitlab/gitlab.rb" | cut -d' ' -f1)
if [[ $(cat "$GL_SUM" 2>/dev/null) != "$sum" ]]; then
  systemctl --user is-active -q gitlab.service && systemctl --user restart gitlab.service
  echo "$sum" > "$GL_SUM"
fi

# mdns-aliases.sh is run from the repo by the running service, so a changed name list
# needs a restart of homelab-mdns (same checksum approach as gitlab.rb).
MDNS_SUM="${HOME}/.config/homelab/mdns-aliases.sha256"
sum=$(sha256sum "$REPO/mdns-aliases.sh" | cut -d' ' -f1)
if [[ $(cat "$MDNS_SUM" 2>/dev/null) != "$sum" ]]; then
  systemctl --user restart homelab-mdns.service || rc=1
  echo "$sum" > "$MDNS_SUM"
fi

# nginx conf.d is bind-mounted too: validate, then reload in place (no restart).
if systemctl --user is-active -q nginx.service; then
  podman exec nginx nginx -t >/dev/null && podman exec nginx nginx -s reload
fi

systemctl --user --no-pager --type=service --state=failed list-units 'homelab*' nginx.service gitlab.service || true
if (( rc )); then echo "==> some units failed, see above" >&2; exit 1; fi
echo "==> done. nginx: http://homelab.local"
